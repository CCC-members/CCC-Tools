

% Load surface
surf_path = 'tess_cortex_concat_02_8000V_fix.mat';

Cortex = load(surf_path);

Vertices = Cortex.Vertices;
Faces = Cortex.Faces;
SulciMap = Cortex.SulciMap;
fig = figure;
patch('Faces',Faces, ...
    'Vertices',Vertices, ...
    'FaceVertexCData',SulciMap, ...
    'FaceColor','interp', ...
    'EdgeColor','none', ...
    'AlphaDataMapping', 'none', ...
    'EdgeColor',        'none', ...
    'EdgeAlpha',        1, ...
    'BackfaceLighting', 'lit', ...
    'AmbientStrength',  0.5, ...
    'DiffuseStrength',  0.5, ...
    'SpecularStrength', 0.2, ...
    'SpecularExponent', 1, ...
    'SpecularColorReflectance', 0.5, ...
    'FaceLighting',     'gouraud', ...
    'EdgeLighting',     'gouraud', ...
    'FaceAlpha',.99);


figures     = {fig, fig, fig, fig};
fig_out     = merge_figures("BEM surfaces registration", "BEM surfaces registration", figures,...
    'rows', 2, 'cols', 2,'axis_on',{'off','off','off','off'},...
    'colorbars',{'off','off','off','off'},...
    'view_orient',{[0,90],[90,360],[1,180],[0,360]});